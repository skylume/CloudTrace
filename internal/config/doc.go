// Package config 负责设置模型、默认值、校验、原子持久化与数据目录解析。
//
// 设计约束：
//   - Config 是**强类型值对象**，所有任务参数都收敛到这里，
//     任何包都不得持有包级可变状态；
//   - 字段名即前后端契约字段名；
//   - 每个键都可关联一个 ParamOrigin（default / preset / user），
//     这是「自动逻辑绝不覆盖用户的显式选择」的落地依据；
//   - 配置损坏时**回退默认值 + 备份原文件**，不阻断启动。
//
// 本包只依赖标准库与 internal/model。
//
// 当前实现了扫描、历史与数据、界面、服务面板、高级五组配置；
// 测速、数据源、网络、ASN 与地理、导出、通知等分组随后续功能补齐。
